// 预解析为坐标点数组，渲染时直接用（避免每帧解析字符串）
const POINTS = {};
for (const [ch, rows] of Object.entries(G)) {
  const pts = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '1') pts.push([x, y]);
  });
  POINTS[ch] = pts;
}

export function glyphPoints(ch) {
  return POINTS[ch] ?? null; // null = 无字形（多为中文，调用方回退）
}

export function hasGlyph(ch) {
  return ch in G;
}

